import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { spawnSync } from "node:child_process";
const root = fileURLToPath(new URL("../", import.meta.url));
const work = path.join(root, "work", "party-tests"); mkdirSync(work, { recursive: true });
await build({ entryPoints: [path.join(root, "tests/party.test.ts")], bundle: true, platform: "node", format: "esm", outfile: path.join(work, "tests.mjs") });
const result = spawnSync(process.execPath, ["--test", path.join(work, "tests.mjs")], { stdio: "inherit" });
process.exitCode = result.status ?? 1;
